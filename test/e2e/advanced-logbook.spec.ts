import { test, expect } from "./fixtures";
import { PrismaClient } from "@prisma/client";
import { existsSync, readFileSync, rmSync } from "node:fs";
import { DEV_MAGIC_LINK_FILE } from "@/lib/dev-magic-link";
import { METRICS_VERSION } from "@/lib/flights/analysis-state";
import { openAdvancedLogbook, expectAdvancedLogbookFits } from "./helpers";

test("advanced logbook fits the viewport, stages grouped edits/deletions and protects exit", async ({ page }, testInfo) => {
  test.setTimeout(120_000);
  const handle=`advanced${Date.now()}`.slice(0,20);
  rmSync(DEV_MAGIC_LINK_FILE,{force:true});
  await page.goto("/sign-in");
  await page.getByPlaceholder("you@example.com").fill(`${handle}@test.local`);
  await page.getByRole("button",{name:/send magic link/i}).click();
  await expect(page.getByRole("heading",{name:/check your email/i})).toBeVisible();
  await expect.poll(()=>existsSync(DEV_MAGIC_LINK_FILE)&&readFileSync(DEV_MAGIC_LINK_FILE,"utf8").startsWith("http")).toBeTruthy();
  await page.goto(readFileSync(DEV_MAGIC_LINK_FILE,"utf8").trim());
  await page.getByRole("button",{name:/keep me signed in/i}).click();
  await page.locator('input[name="handle"]').fill(handle);
  await page.locator('input[name="display_name"]').fill("Advanced Pilot");
  await page.getByRole("button",{name:/create my logbook/i}).click();
  await expect(page).toHaveURL(/\/logbook$/);
  const db=new PrismaClient();
  try {
    const owner=await db.profile.findUniqueOrThrow({where:{handle}});
    const rows=[];
    for(let i=0;i<30;i++)rows.push(await db.flight.create({data:{ownerId:owner.id,visibility:(["private","friends","public"] as const)[i%3],recordingKind:i%2?"igc":"logbook",source:i%2?"web_upload":"manual_entry",status:"ready",xcStatus:"not_recorded",metricsVersion:METRICS_VERSION,flightDate:new Date(`2026-10-${String(30-i).padStart(2,"0")}`),glider:i%2?"Wing B · Advance Iota DLS special edition 25":"Wing A",takeoffSiteName:"Tiger Mountain",landingSiteName:i%3?"Tiger Mountain":"Tiger LZ",durationS:3600,maxAltM:1500,maxClimbMs:12.5,notes:i%2?"Keep this existing note.":null}}));
    await page.goto("/logbook");
    await page.getByRole("button",{name:"Select Wings",exact:true}).click();
    await page.getByRole("checkbox",{name:/Wing B/}).uncheck();
    await page.keyboard.press("Escape");
    await expect(page.getByRole("status").filter({hasText:"15 of 30 flights"})).toBeVisible();
    const main=await openAdvancedLogbook(page);
    await expect(main.getByRole("listitem")).toHaveCount(15);
    await main.getByRole("button",{name:"Clear filters",exact:true}).click();
    await expect(main.getByRole("button",{name:"Clear filters",exact:true})).toHaveCount(0);
    await expect(main.getByRole("button",{name:"Discard draft",exact:true})).toHaveCount(0);
    await expect(main.getByRole("button",{name:"Logbook",exact:true})).toHaveCount(0);
    const sweep=[];
    const sizes=[{width:2560,height:900},{width:1440,height:900},...Array.from({length:51},(_,i)=>({width:1120-i*16,height:900})),{width:526,height:900},{width:527,height:900},{width:390,height:844},{width:320,height:640},{width:390,height:540}];
    for(const size of sizes){
      await page.setViewportSize(size);await expectAdvancedLogbookFits(page);
      const layout=await main.locator(`[data-flight-id="${rows[1].id}"]`).evaluate(row=>{
        const box=(name:string)=>row.querySelector(`[data-editor-column="${name}"]`)!.getBoundingClientRect();
        const wing=row.querySelector('[data-editor-column="wing"] button > span')!;
        return {areas:getComputedStyle(row.querySelector('[data-editor-column="date"]')!.parentElement!).gridTemplateAreas,wingWidth:box('wing').width,visibilityWidth:box("visibility").width,notesWidth:box("notes").width,stacked:Math.abs(box("altitude").left-box("climb").left)<1&&box("climb").top>=box("altitude").bottom,metricsAboveBadges:box("xc").bottom<=box("friends").top,twoBadgeRows:box("friends").bottom<=box("visibility").top,siteAboveIdentity:box("site").bottom<=Math.min(box("date").top,box("wing").top),wingHeight:wing.getBoundingClientRect().height,wingLineHeight:parseFloat(getComputedStyle(wing).lineHeight)};
      });
      expect(layout.wingHeight).toBeLessThanOrEqual(layout.wingLineHeight*3+1);
      const filterLabels=await main.locator('[data-filter-key] [data-filter-label]').evaluateAll(labels=>labels.map(label=>getComputedStyle(label).visibility!=="hidden"));
      expect(filterLabels.every((shown,index)=>shown||filterLabels.slice(index+1).every(next=>!next))).toBe(true);
      const tailAreas=await main.locator('[data-trailing-filters]').evaluate(element=>getComputedStyle(element).gridTemplateAreas.replaceAll('source','upload'));
      // On the narrowest phones, filters remain one compact row while badges
      // use the spare space beside the flight's details.
      if(size.width>376) expect(tailAreas).toBe(await main.locator(`[data-flight-id="${rows[0].id}"] [data-editor-column="friends"]`).evaluate(element=>getComputedStyle(element.parentElement!).gridTemplateAreas));
      if(size.width<=700){
        const heading=await main.getByText('Advanced edit',{exact:true}).boundingBox(), done=await main.getByRole('button',{name:'Done editing',exact:true}).boundingBox();
        expect(Math.abs(heading!.y+heading!.height/2-done!.y-done!.height/2)).toBeLessThan(1);
      }
      sweep.push({size,...layout,filterLabels});
      if([2560,1440,800,640,560,480,400,320,390].includes(size.width)) await page.screenshot({path:testInfo.outputPath(`advanced-${size.width}-${size.height}.png`),fullPage:true});
    }
    await testInfo.attach('width-sweep',{body:JSON.stringify(sweep,null,2),contentType:'application/json'});
    const sideBySide=sweep.filter(entry=>entry.areas.includes('"site site details"'));
    expect(sideBySide.length).toBeGreaterThan(2);
    expect(sideBySide.some(entry=>entry.wingHeight>=entry.wingLineHeight*2.9)).toBe(true);
    await page.setViewportSize({width:1440,height:900});
    await expect.poll(()=>main.locator('[data-filter-key][data-compact=true]').count()).toBe(0);
    await main.getByRole('button',{name:'Select Wings',exact:true}).click();
    await page.getByRole('group',{name:'Wings choices'}).getByRole('button',{name:'Sort wing ascending',exact:true}).click();
    await expect(main.locator('[data-current-sort]')).toHaveAttribute('aria-label','Current sort: Wing ascending');
    await expect(main.getByRole('button',{name:'Clear filters',exact:true})).toHaveCount(0);
    await page.keyboard.press('Escape');
    await page.setViewportSize({width:600,height:900});
    await expect(main.getByRole('button',{name:/^Sort /})).toHaveCount(0);
    await main.getByRole('button',{name:'Select Wings',exact:true}).click();
    const wingChoices=page.getByRole('group',{name:'Wings choices'});
    await expect(wingChoices.getByRole('button',{name:'Sort wing ascending',exact:true})).toHaveAttribute('aria-pressed','true');
    await wingChoices.getByRole('button',{name:'Sort wing descending',exact:true}).click();
    await expect(main.locator('[data-current-sort]')).toHaveAttribute('aria-label','Current sort: Wing descending');
    await expect(main.getByRole('listitem')).toHaveCount(30);
    await expect(wingChoices.getByRole('checkbox',{name:'Wing A',exact:true})).toBeChecked();
    await wingChoices.getByRole('button',{name:'Sort wing ascending',exact:true}).click();
    await page.keyboard.press('Escape');
    await page.setViewportSize({width:1440,height:900});
    await main.getByRole('button',{name:'Select Wings',exact:true}).click();
    await expect(wingChoices.getByRole('button',{name:'Sort wing ascending',exact:true})).toHaveAttribute('aria-pressed','true');
    await page.keyboard.press('Escape');
    await main.getByRole('button',{name:'Select Dates',exact:true}).click();
    await page.getByRole('group',{name:'Dates choices'}).getByRole('button',{name:'Sort date descending',exact:true}).click();
    await page.keyboard.press('Escape');
    await page.setViewportSize({width:390,height:844});
    await main.getByRole('button',{name:'Select Visibility',exact:true}).click();
    await expect(page.getByRole('group',{name:'Visibility choices'}).getByText('Visibility',{exact:true})).toBeVisible();
    await page.getByRole('group',{name:'Visibility choices'}).getByRole('button',{name:'None',exact:true}).click();
    await expect(main.getByRole('button',{name:'Clear filters',exact:true})).toBeVisible();
    await page.getByRole('group',{name:'Visibility choices'}).getByRole('checkbox',{name:'Private',exact:true}).check();
    await page.keyboard.press('Escape');
    const summaryBounds=await main.locator('[data-filter-summary] [role="status"]').boundingBox(), clearBounds=await main.getByRole('button',{name:'Clear filters',exact:true}).boundingBox();
    expect(clearBounds!.y).toBeGreaterThanOrEqual(summaryBounds!.y+summaryBounds!.height);
    await expectAdvancedLogbookFits(page);
    await page.screenshot({path:testInfo.outputPath('advanced-filter-summary-shared-row.png'),fullPage:true});
    await main.getByRole('button',{name:'Clear filters',exact:true}).click();
    await expect(main.getByRole('button',{name:'Clear filters',exact:true})).toHaveCount(0);
    await expect(main.getByRole('listitem')).toHaveCount(30);
    await main.getByRole('button',{name:'Select all',exact:true}).click();
    await main.getByRole('button',{name:'Edit selected Wing',exact:true}).click();
    await expect(page.getByRole('dialog').getByRole('heading',{name:'Edit Wing',exact:true})).toBeVisible();
    await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click();
    await main.getByRole('button',{name:'Select none',exact:true}).click();
    await main.locator(`[data-flight-id="${rows[0].id}"]`).getByRole('button',{name:/^Edit Notes:/}).click();
    await page.getByRole('dialog').getByLabel('Notes',{exact:true}).fill('Temporary draft to check the footer.');
    await page.getByRole('dialog').getByRole('button',{name:'Add to draft',exact:true}).click();
    await page.setViewportSize({width:320,height:640});
    await expectAdvancedLogbookFits(page);
    await expect(main.getByRole('button',{name:'Review changes',exact:true})).toBeEnabled();
    await expect(main.getByRole('button',{name:'Discard draft',exact:true})).toBeVisible();
    await page.screenshot({path:testInfo.outputPath('advanced-footer-pending-mobile.png'),fullPage:true});
    await main.getByRole('button',{name:'Discard draft',exact:true}).click();
    await expect(main.getByRole('button',{name:'Discard draft',exact:true})).toHaveCount(0);
    await expect(main.getByText('All draft changes discarded.',{exact:true})).toBeVisible();
    await expect(main.getByRole('button',{name:'Review changes',exact:true})).toBeDisabled();
    await expectAdvancedLogbookFits(page);
    await page.screenshot({path:testInfo.outputPath('advanced-footer-discarded-mobile.png'),fullPage:true});
    await page.setViewportSize({width:600,height:900});
    const siteLine=await main.locator(`[data-flight-id="${rows[0].id}"] [data-editor-column="site"]`).evaluate(site=>Array.from(site.querySelectorAll('button')).map(button=>button.getBoundingClientRect().top));
    expect(siteLine).toHaveLength(2);
    expect(Math.abs(siteLine[0]-siteLine[1])).toBeLessThan(1);
    await page.setViewportSize({width:1440,height:900});
    const badgeColors=await main.locator('[data-flight-id]').evaluateAll(rows=>rows.slice(0,3).map(row=>({visibility:getComputedStyle(row.querySelector('[data-editor-column="visibility"] button')!).backgroundColor,notes:getComputedStyle(row.querySelector('[data-editor-column="notes"] button')!).backgroundColor})));
    expect(new Set(badgeColors.map(colors=>colors.visibility)).size).toBe(3);
    expect(badgeColors[0].notes).not.toBe(badgeColors[1].notes);
    expect(badgeColors.every(colors=>colors.visibility!=="rgba(0, 0, 0, 0)"&&colors.notes!=="rgba(0, 0, 0, 0)")).toBe(true);
    const first=main.locator(`[data-flight-id="${rows[0].id}"]`),second=main.locator(`[data-flight-id="${rows[1].id}"]`);
    await first.getByRole("checkbox").check();await second.getByRole("checkbox").check();
    await main.getByRole("combobox",{name:"Edit selected field"}).selectOption("notes");
    const dialog=page.getByRole("dialog");
    await expect(dialog.getByText("1 flight does not have this value set.",{exact:false})).toBeVisible();
    await dialog.getByLabel("Action",{exact:true}).selectOption("fill");
    await dialog.getByLabel("Notes",{exact:true}).fill("New note for the empty field.");
    await dialog.getByRole("button",{name:"Add to draft",exact:true}).click();
    await first.getByRole("button",{name:/^Edit Wing:/}).click();
    await dialog.getByLabel("Wing",{exact:true}).fill("New wing name");
    await dialog.getByRole("button",{name:"Add to draft",exact:true}).click();
    await main.getByRole("button",{name:"Review changes",exact:true}).click();
    await expect(dialog.getByRole("heading",{level:3})).toHaveCount(1);
    await expect(dialog.getByRole("button",{name:/^Cancel .* change$/})).toHaveCount(2);
    await dialog.getByRole("button",{name:"Cancel Wing change",exact:true}).click();
    await dialog.getByRole("button",{name:"Keep editing",exact:true}).click();
    await main.getByRole("button",{name:"Select none",exact:true}).click();
    await second.getByRole("checkbox").check();
    await main.getByRole("button",{name:"Delete selected",exact:true}).click();
    await expect(dialog).not.toBeVisible();
    await expect(second.getByText("Pending deletion",{exact:false})).toBeVisible();
    await expect(second.getByRole("checkbox")).not.toBeChecked();
    await expect(main.getByText("0 selected",{exact:true})).toBeVisible();
    await main.getByRole("button",{name:"Done editing",exact:true}).click();
    await expect(dialog.getByRole("heading",{name:"You have 2 unsaved changes"})).toBeVisible();
    await dialog.getByRole("button",{name:"Keep editing",exact:true}).click();
    await main.getByRole("button",{name:"Review changes",exact:true}).click();
    await expect(dialog.getByRole("heading",{name:"Delete 1 flight",exact:true})).toBeVisible();
    await dialog.getByRole("button",{name:"Save changes",exact:true}).click();
    await expect(dialog).not.toBeVisible();
    await expect(main.getByText("No unsaved changes",{exact:true})).toBeVisible();
    expect(await db.flight.findUnique({where:{id:rows[1].id}})).toBeNull();
    expect((await db.flight.findUniqueOrThrow({where:{id:rows[0].id}})).notes).toBe("New note for the empty field.");
    expect((await db.flight.findUniqueOrThrow({where:{id:rows[0].id}})).glider).toBe("Wing A");
    await main.getByRole("button",{name:"Done editing",exact:true}).click();
    await expect(page).toHaveURL(/\/logbook$/);
    await expect(page.locator(`a[href="/flights/${rows[0].id}"]`)).toBeVisible();
    await openAdvancedLogbook(page);
    await main.locator(`[data-flight-id="${rows[0].id}"]`).getByRole("button",{name:/^Edit Notes:/}).click();
    await dialog.getByLabel("Notes",{exact:true}).fill("Save this note and leave.");
    await dialog.getByRole("button",{name:"Add to draft",exact:true}).click();
    await page.getByRole("banner").getByRole("link",{name:"Feed",exact:true}).click();
    await expect(dialog.getByRole("heading",{name:"You have 1 unsaved change"})).toBeVisible();
    await dialog.getByRole("button",{name:"Keep editing",exact:true}).click();
    await main.getByRole("button",{name:"Done editing",exact:true}).click();
    await dialog.getByRole("button",{name:"Review changes",exact:true}).click();
    await dialog.getByRole("button",{name:"Save and return to logbook",exact:true}).click();
    await expect(page).toHaveURL(/\/logbook$/);
    await page.reload();
    expect((await db.flight.findUniqueOrThrow({where:{id:rows[0].id}})).notes).toBe("Save this note and leave.");
  } finally {await db.$disconnect();}
});
